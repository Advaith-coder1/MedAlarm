function makeRecord(
  id: string, medId: string, userId: string,
  date: string, time: string,
  status: DoseRecord['status'],
  takenOffset?: number
): DoseRecord {
  const scheduledTime = `${date}T${time}:00`;
  const takenAt = takenOffset !== undefined
    ? format(new Date(scheduledTime).getTime() + takenOffset * 60000, "yyyy-MM-dd'T'HH:mm:ss")
    : undefined;
  return { id, medicationId: medId, userId, scheduledTime, takenAt, status };
}

